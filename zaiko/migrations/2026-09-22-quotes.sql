-- ============================================================
-- 見積（希望受付 → 見積作成 → 顧客提示 → 顧客承認 → 契約準備）
--   2026-09-22（2026-09-21-sale-catalog.sql の後に流す）
--
--   案件（inventory_deals）1件に、版（rev）を持つ見積をぶら下げます。
--
--   決めていること
--     ・提示済みの見積は編集できない。直すときは複製して新しい版を作る。
--       （提示したあとに金額が変わると、どれが正なのか分からなくなるため）
--     ・新しい版を提示したら、それより前の提示済みの版は自動で失効させる。
--       （お客様が古いURLから承認してしまう事故を防ぐため）
--     ・明細は「そのときの内容」を写して持つ（品名・スペック・単価）。
--       あとから商品マスタが変わっても、出した見積は変わらない。
--     ・販売・レンタル・初期設定費・キッティング費・設置費・ネットワーク費・
--       月額サービス・研修 を、1つの見積に混在できる。
--     ・顧客の［この内容で進める］は契約ではなく意思表示。
--       **この時点で在庫（inventory_items）は一切動かさない。**
--       inv_sale_reserve() も inv_rental_allocate() も呼ばない。
--     ・Stripeはまだ入れない（Phase 3）。
--
--   入っているもの
--     inventory_quotes        見積（案件×版）
--     inventory_quote_items   見積明細
--     inv_quote_totals        合計（初期費用・月額・消費税・税込）
--     inv_quote_create()      案件から見積を作る（前の版の複製も）
--     inv_quote_item_save()   明細の追加・書き換え
--     inv_quote_item_delete() 明細の削除
--     inv_quote_present()     お客様に提示する（tokenを発行し、前の版を失効）
--     inv_quote_cancel()      取消
--     inv_quote_public()      顧客ページが読む（社内メモ・原価は返さない・匿名可）
--     inv_quote_decide()      顧客の［進める］［相談する］（匿名可・在庫は動かさない）
--
--   何度流しても同じ結果になります。
--
--   実行後の確認
--     select id, deal_id, rev, quote_no, status, valid_until from public.inventory_quotes;
--     select * from public.inv_quote_totals;
-- ============================================================

