  decided_at    timestamptz,
  decided_by    text,          -- お客様が入力したお名前
  customer_message text,       -- ［内容について相談する］で書かれた内容

  actor         text,          -- 最後に動かした社内の人
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),

  unique (deal_id, rev)
);

